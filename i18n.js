// ---- i18n Engine ----

let currentLang = localStorage.getItem('humaniwork_lang') || 'en';

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('humaniwork_lang', lang);
    document.documentElement.lang = lang;

    const t = translations[lang];
    if (!t) return;

    // Update all data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (!t[key]) return;

        if (el.hasAttribute('data-i18n-html')) {
            el.innerHTML = t[key];
        } else {
            el.textContent = t[key];
        }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (t[key]) el.placeholder = t[key];
    });

    // Update page title
    const titles = {
        en: "Humaniwork — Technology that works for everyone",
        es: "Humaniwork — Tecnología que trabaja para todos"
    };
    document.title = titles[lang] || titles.en;

    // Update meta description
    const descriptions = {
        en: "Humaniwork is Spain's AI platform for workforce integration intelligence. Helping municipalities, incubators, and employers turn migration into shared prosperity.",
        es: "Humaniwork es la plataforma de IA de España para inteligencia de integración laboral. Ayudamos a ayuntamientos, incubadoras y empleadores a convertir la migración en prosperidad compartida."
    };
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) metaDesc.content = descriptions[lang] || descriptions.en;

    // Update active button state
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });
}

// Initialize on load
document.addEventListener('DOMContentLoaded', () => {
    // Attach click handlers to language buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            setLanguage(btn.getAttribute('data-lang'));
        });
    });

    // Apply saved language
    setLanguage(currentLang);
});
